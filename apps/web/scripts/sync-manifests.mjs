// Copies deployment manifests published by Astra (packages/chain-config/deployments/<chainId>.json)
// into src/generated/manifests.ts so the app never statically imports a file that may not exist.
// No manifest -> the generated map is empty -> every service resolves to FIXTURE mode.
// Validation happens at runtime in src/lib/manifest.ts; `--strict` additionally fails this script
// when a manifest is unreadable JSON or its chainId does not match its file name.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(here, "..");
const repoRoot = resolve(webRoot, "../..");
const sourceDir = process.env.PERIDOT_DEPLOYMENTS_DIR
  ? resolve(process.env.PERIDOT_DEPLOYMENTS_DIR)
  : join(repoRoot, "packages/chain-config/deployments");
const strict = process.argv.includes("--strict");

const entries = {};
const problems = [];
if (existsSync(sourceDir)) {
  for (const file of readdirSync(sourceDir).sort()) {
    const match = /^(\d+)\.json$/.exec(file);
    if (!match) continue;
    const chainId = match[1];
    const text = readFileSync(join(sourceDir, file), "utf8");
    try {
      const json = JSON.parse(text);
      if (String(json?.chainId) !== chainId) problems.push(`${file}: chainId ${json?.chainId} does not match file name`);
      entries[chainId] = { ok: true, json };
    } catch (error) {
      problems.push(`${file}: invalid JSON (${error.message})`);
      entries[chainId] = { ok: false, error: `Invalid JSON: ${error.message}` };
    }
  }
}

const outDir = join(webRoot, "src/generated");
mkdirSync(outDir, { recursive: true });
const label = relative(repoRoot, sourceDir) || ".";
const body = `// GENERATED by scripts/sync-manifests.mjs. Do not edit, do not commit.
// Source directory: ${label}
export type RawManifestEntry = { ok: true; json: unknown } | { ok: false; error: string };
export const RAW_MANIFESTS: Record<string, RawManifestEntry> = ${JSON.stringify(entries, null, 2)};
export const MANIFEST_SOURCE_DIR = ${JSON.stringify(label)};
`;
writeFileSync(join(outDir, "manifests.ts"), body);

// Evidence recorded by Astra (A1/A5). Shown on /circuits and /sentinel/activity with its own provenance labels,
// clearly separated from fixtures. Missing files become null.
function readEvidence(relativePath) {
  const path = join(repoRoot, relativePath);
  if (!existsSync(path)) return null;
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch (error) {
    problems.push(`${relativePath}: invalid JSON (${error.message})`);
    return null;
  }
}
const a5Dir = join(repoRoot, "evidence/a5");
const settlementFile = existsSync(a5Dir) ? readdirSync(a5Dir).filter((file) => /^settlement-[0-9a-f]+\.json$/.test(file)).sort().at(-1) : undefined;
const evidence = {
  mainnetReads: { file: "evidence/a1/mainnet-reads.json", json: readEvidence("evidence/a1/mainnet-reads.json") },
  forkPolicies: { file: "evidence/a1/fork-policy-evaluations.json", json: readEvidence("evidence/a1/fork-policy-evaluations.json") },
  localAutoRepay: { file: "evidence/astra/local-auto-repay.json", json: readEvidence("evidence/astra/local-auto-repay.json") },
  testnetAutoRepay: { file: "evidence/testnet/keeper-auto-repay-1952.json", json: readEvidence("evidence/testnet/keeper-auto-repay-1952.json") },
  forkSettlement: settlementFile ? { file: `evidence/a5/${settlementFile}`, json: readEvidence(`evidence/a5/${settlementFile}`) } : { file: null, json: null },
  // Sentinel Connect: the external MCP client's seven-step run on public testnet 1952 and the server's tool catalogue.
  connectTranscript: { file: "evidence/session5-mcp/flagship-1952.json", json: readEvidence("evidence/session5-mcp/flagship-1952.json") },
  connectTools: { file: "evidence/session5-mcp/tools.json", json: readEvidence("evidence/session5-mcp/tools.json") },
  // Policy vectors rehearsed on a mainnet FORK (never public): used to test the input encoders and as labelled examples.
  tapeoutVectors: { file: "evidence/session5-d8b/proposal-and-fork.json", json: slimVectors(readEvidence("evidence/session5-d8b/proposal-and-fork.json")) },
  // Sentinel v2 on public testnet 1952: owner supply, swap-only grant, mined EXECUTION denial, operator swap (mock venue).
  v2Demo: { file: "evidence/session6-v2/1952.json", json: readEvidence("evidence/session6-v2/1952.json") },
  // Two MINED reverts on public testnet 1952: one stopped by the account policy only, one by the market policy only.
  publicRejections: { file: "evidence/session6-rejections/public-1952.json", json: slimRejections(readEvidence("evidence/session6-rejections/public-1952.json")) },
};
function slimRejections(json) {
  if (!json || !Array.isArray(json.rejections)) return null;
  const keep = ["market", "controller", "account", "amountRaw", "postLtvBps", "block", "blockHash", "hash", "status", "logs", "gasUsed", "from", "to", "reasonSource", "minedRevert", "decisions", "storedDebtBefore", "storedDebtAfter"];
  return { label: json.label ?? null, chainId: json.chainId ?? null, fork: json.fork ?? null, profile: json.profile ?? null, rejections: json.rejections.map((entry) => Object.fromEntries(keep.map((key) => [key, entry[key] ?? null]))) };
}
// Only what the app shows or tests: the fork calldata and envelopes stay out of the bundle (the selector is kept).
function slimVectors(json) {
  if (!json || !Array.isArray(json.evaluations)) return null;
  return {
    classification: json.classification ?? null,
    pin: json.pin ? { chainId: json.pin.chainId, number: json.pin.number, hash: json.pin.hash } : null,
    evaluations: json.evaluations.map((entry) => ({
      label: entry.label,
      dimensions: entry.dimensions,
      netlistHash: entry.netlistHash,
      vectors: (entry.vectors ?? []).map((vector) => ({ context: vector.context, inputs: vector.inputs, output: vector.output, observedOutput: vector.observedOutput, selector: typeof vector.localEvalCalldata === "string" ? vector.localEvalCalldata.slice(0, 10) : null })),
    })),
  };
}
writeFileSync(
  join(outDir, "evidence.ts"),
  `// GENERATED by scripts/sync-manifests.mjs. Do not edit, do not commit.
export const RAW_EVIDENCE: Record<${Object.keys(evidence).map((key) => JSON.stringify(key)).join(" | ")}, { file: string | null; json: unknown }> = ${JSON.stringify(evidence, null, 2)};
`,
);

// Configuration published by the contracts team that is NOT part of the v1 deployment manifest. Every entry may be
// absent; the app then hides or labels the feature. One file per concern, so each has a single place to update:
//   tapeout    packages/chain-config/expansion/tapeout-196.json   Peridot's circuits on X Layer mainnet. \`publishedId\`
//              and \`publicReceipt\` are null until the founder publishes; /circuits reads the IDs from here only.
//   expansion  packages/chain-config/expansion/deployments/<chainId>.json   v2 accounts and adapters (absent = hidden).
//   activity   packages/chain-config/activity/<chainId>.json   indexed activity snapshot (absent = browser scan only).
// PERIDOT_TAPEOUT_MANIFEST / PERIDOT_EXPANSION_DIR / PERIDOT_ACTIVITY_DIR override the paths for tests.
function readJsonFile(path) {
  if (!existsSync(path)) return null;
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch (error) {
    problems.push(`${relative(repoRoot, path)}: invalid JSON (${error.message})`);
    return null;
  }
}
function readChainDir(dir) {
  const found = {};
  if (!existsSync(dir)) return found;
  for (const file of readdirSync(dir).sort()) {
    const match = /^(\d+)\.json$/.exec(file);
    if (match) found[match[1]] = readJsonFile(join(dir, file));
  }
  return found;
}
const tapeoutPath = process.env.PERIDOT_TAPEOUT_MANIFEST ? resolve(process.env.PERIDOT_TAPEOUT_MANIFEST) : join(repoRoot, "packages/chain-config/expansion/tapeout-196.json");
const expansionDir = process.env.PERIDOT_EXPANSION_DIR ? resolve(process.env.PERIDOT_EXPANSION_DIR) : join(repoRoot, "packages/chain-config/expansion/deployments");
const activityDir = process.env.PERIDOT_ACTIVITY_DIR ? resolve(process.env.PERIDOT_ACTIVITY_DIR) : join(repoRoot, "packages/chain-config/activity");
const config = {
  tapeout: { file: relative(repoRoot, tapeoutPath), json: readJsonFile(tapeoutPath) },
  expansion: { dir: relative(repoRoot, expansionDir), byChain: readChainDir(expansionDir) },
  activity: { dir: relative(repoRoot, activityDir), byChain: readChainDir(activityDir) },
};
writeFileSync(
  join(outDir, "config.ts"),
  `// GENERATED by scripts/sync-manifests.mjs. Do not edit, do not commit.
export const RAW_CONFIG: { tapeout: { file: string; json: unknown }; expansion: { dir: string; byChain: Record<string, unknown> }; activity: { dir: string; byChain: Record<string, unknown> } } = ${JSON.stringify(config, null, 2)};
`,
);
const ids = Object.keys(entries);
console.log(`[sync-manifests] ${ids.length ? `found manifests for chain(s) ${ids.join(", ")}` : "no deployment manifests found: FIXTURE MODE"} (${label})`);
for (const problem of problems) console.warn(`[sync-manifests] WARNING ${problem}`);
if (strict && problems.length) process.exit(1);
